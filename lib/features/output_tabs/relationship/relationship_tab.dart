                              color: themeColor,
                            ),
                          ],
                        ),
                      ),
                    ),
                    // Expanded content
                    if (isExpanded) ...[
                      Padding(
                        padding: const EdgeInsets.all(20),
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            // Unconscious Pattern
                            if (scenario.unconsciousPattern != null)
                              _buildScenarioSection(
                                context,
                                'Unconscious Pattern',
                                scenario.unconsciousPattern!,
                                Icons.psychology_alt,
                                Colors.grey.shade600,
                              ),
                            // Two paths
                            const SizedBox(height: 16),
                            Row(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                // Unconscious path
