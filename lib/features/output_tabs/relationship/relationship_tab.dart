class _WhatIfScenariosTab extends StatefulWidget {
  final RelationshipOutput output;
  final Color accentColor;

  const _WhatIfScenariosTab({required this.output, required this.accentColor});

  @override
  State<_WhatIfScenariosTab> createState() => _WhatIfScenariosTabState();
}

class _WhatIfScenariosTabState extends State<_WhatIfScenariosTab> {
  final Set<int> _revealedSections = {};
  int? _expandedScenario;

  @override
  void initState() {
    super.initState();
    _startProgressiveReveal();
  }

  void _startProgressiveReveal() {
    final scenarios = widget.output.whatIfScenarios;
    for (int i = 0; i <= scenarios.length; i++) {
      Future.delayed(Duration(milliseconds: 150 * i), () {
        if (mounted) setState(() => _revealedSections.add(i));
      });
    }
  }

  IconData _getThemeIcon(String theme) {
    switch (theme.toLowerCase()) {
      case 'conflict':
        return Icons.flash_on;
      case 'intimacy':
        return Icons.favorite;
      case 'trust':
        return Icons.security;
      case 'autonomy':
        return Icons.flight_takeoff;
      case 'authority':
        return Icons.gavel;
      case 'jealousy':
        return Icons.warning;
      case 'loyalty':
        return Icons.handshake;
      case 'boundaries':
        return Icons.border_all;
      case 'power_imbalance':
        return Icons.balance;
      case 'priorities':
        return Icons.priority_high;
      default:
        return Icons.psychology;
    }
  }

  Color _getThemeColor(String theme) {
    switch (theme.toLowerCase()) {
      case 'conflict':
        return Colors.red;
      case 'intimacy':
        return Colors.pink;
      case 'trust':
        return Colors.blue;
      case 'autonomy':
        return Colors.teal;
      case 'authority':
        return Colors.deepPurple;
      case 'jealousy':
        return Colors.orange;
      case 'loyalty':
        return Colors.indigo;
      case 'boundaries':
        return Colors.amber;
      case 'power_imbalance':
        return Colors.brown;
      case 'priorities':
        return Colors.cyan;
      default:
        return Colors.purple;
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final scenarios = widget.output.whatIfScenarios;

    if (scenarios.isEmpty) {
      return Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(Icons.psychology, size: 48, color: widget.accentColor.withOpacity(0.5)),
            const SizedBox(height: 16),
            Text('What-If scenarios not available', style: theme.textTheme.bodyLarge),
            const SizedBox(height: 8),
            Text(
              'Try regenerating the relationship analysis',
              style: theme.textTheme.bodySmall?.copyWith(color: theme.colorScheme.onSurfaceVariant),
            ),
          ],
        ),
      );
    }

    return ListView(
      padding: const EdgeInsets.all(16),
      children: [
        // Header
        AnimatedOpacity(
          duration: const Duration(milliseconds: 400),
          opacity: _revealedSections.contains(0) ? 1.0 : 0.3,
          child: Card(
            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
            child: Padding(
              padding: const EdgeInsets.all(20),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      Container(
                        padding: const EdgeInsets.all(12),
                        decoration: BoxDecoration(
                          gradient: LinearGradient(
                            colors: [widget.accentColor, widget.accentColor.withOpacity(0.7)],
                          ),
                          borderRadius: BorderRadius.circular(12),
                        ),
                        child: const Icon(Icons.psychology, color: Colors.white, size: 28),
                      ),
                      const SizedBox(width: 16),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              'What-If Scenarios',
                              style: theme.textTheme.titleLarge?.copyWith(fontWeight: FontWeight.w700),
                            ),
                            const SizedBox(height: 4),
                            Text(
                              'Key relationship moments with conscious paths',
                              style: theme.textTheme.bodySmall?.copyWith(
                                color: theme.colorScheme.onSurfaceVariant,
                              ),
                            ),
                          ],
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ),
        ),
        const SizedBox(height: 16),
        // Scenarios
        ...scenarios.asMap().entries.map((entry) {
          final index = entry.key;
          final scenario = entry.value;
          final isRevealed = _revealedSections.contains(index + 1);
          final isExpanded = _expandedScenario == index;
          final themeColor = _getThemeColor(scenario.theme);
          
          return AnimatedOpacity(
            duration: const Duration(milliseconds: 400),
            opacity: isRevealed ? 1.0 : 0.3,
            child: AnimatedContainer(
              duration: const Duration(milliseconds: 400),
              transform: Matrix4.translationValues(isRevealed ? 0 : 20, 0, 0),
              child: Card(
                margin: const EdgeInsets.only(bottom: 16),
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                clipBehavior: Clip.antiAlias,
                child: Column(
                  children: [
                    // Header - always visible
                    InkWell(
                      onTap: () {
