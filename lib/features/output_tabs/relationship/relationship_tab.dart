class _RelationshipMythTab extends ConsumerStatefulWidget {
  final RelationshipOutput output;
  final Color accentColor;

  const _RelationshipMythTab({required this.output, required this.accentColor});

  @override
  ConsumerState<_RelationshipMythTab> createState() => _RelationshipMythTabState();
}

class _RelationshipMythTabState extends ConsumerState<_RelationshipMythTab> {
  final Set<int> _revealedSections = {};

  @override
  void initState() {
    super.initState();
    _startProgressiveReveal();
  }

  void _startProgressiveReveal() {
    for (int i = 0; i < 4; i++) {
      Future.delayed(Duration(milliseconds: 150 * i), () {
        if (mounted) setState(() => _revealedSections.add(i));
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final myth = widget.output.myth;

    if (myth == null) {
      return const Center(child: Text('No myth data available'));
    }

    return ListView(
      padding: const EdgeInsets.all(16),
      children: [
        // Relationship Constellation Card (NEW)
        _buildConstellationSection(),
        const SizedBox(height: 12),
        
        // Title card
        _buildAnimatedCard(
          0,
          _buildSectionCard(
            context,
            title: myth.title ?? 'Your Relationship Myth',
            content: myth.summary ?? '',
            icon: Icons.auto_stories,
            accentColor: widget.accentColor,
            isHighlighted: true,
          ),
        ),
        const SizedBox(height: 12),
        // Story card
        _buildAnimatedCard(
          1,
          _buildSectionCard(
            context,
            title: 'The Story',
            content: myth.story ?? '',
            icon: Icons.menu_book,
            accentColor: const Color(0xFF8B5CF6),
          ),
        ),
        const SizedBox(height: 12),
        // Themes card
        if (myth.themes.isNotEmpty)
          _buildAnimatedCard(
            2,
            _buildThemesCard(context, myth.themes),
          ),
      ],
    );
  }

  Widget _buildAnimatedCard(int index, Widget child) {
    final isRevealed = _revealedSections.contains(index);
    return AnimatedOpacity(
      duration: const Duration(milliseconds: 400),
      opacity: isRevealed ? 1.0 : 0.3,
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 400),
        transform: Matrix4.translationValues(isRevealed ? 0 : 20, 0, 0),
        child: child,
      ),
    );
  }

  Widget _buildConstellationSection() {
    final constellationAsync = ref.watch(relationshipConstellationProvider);

    return constellationAsync.when(
      data: (response) {
        if (response == null || response.relationshipConstellation == null) {
          return const SizedBox.shrink();
        }
        return RelationshipConstellationCard(
          constellation: response.relationshipConstellation!,
        );
      },
      loading: () => Container(
        margin: const EdgeInsets.symmetric(vertical: 8),
        padding: const EdgeInsets.all(24),
        decoration: BoxDecoration(
          color: Theme.of(context).colorScheme.surfaceContainerHighest.withOpacity(0.5),
          borderRadius: BorderRadius.circular(16),
        ),
        child: const Center(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              CircularProgressIndicator(strokeWidth: 2),
              SizedBox(height: 12),
              Text('Loading shared archetypes...'),
            ],
          ),
        ),
      ),
      error: (_, __) => const SizedBox.shrink(),
    );
  }

  Widget _buildSectionCard(
    BuildContext context, {
    required String title,
    required String content,
    required IconData icon,
    required Color accentColor,
    bool isHighlighted = false,
  }) {
    final theme = Theme.of(context);
    
    return Card(
      elevation: isHighlighted ? 4 : 1,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(16),
        side: isHighlighted
            ? BorderSide(color: accentColor.withOpacity(0.3), width: 1.5)
            : BorderSide.none,
      ),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Container(
                  padding: const EdgeInsets.all(8),
                  decoration: BoxDecoration(
                    color: accentColor.withOpacity(0.1),
                    borderRadius: BorderRadius.circular(8),
                  ),
                  child: Icon(icon, color: accentColor, size: 20),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Text(
                    title,
                    style: theme.textTheme.titleMedium?.copyWith(
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 16),
            Text(
              content,
              style: theme.textTheme.bodyMedium?.copyWith(
                height: 1.6,
                fontStyle: isHighlighted ? FontStyle.italic : FontStyle.normal,
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildThemesCard(BuildContext context, List<String> themes) {
    final theme = Theme.of(context);
    
    return Card(
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Container(
                  padding: const EdgeInsets.all(8),
                  decoration: BoxDecoration(
                    color: const Color(0xFF14B8A6).withOpacity(0.1),
                    borderRadius: BorderRadius.circular(8),
                  ),
                  child: const Icon(Icons.tag, color: Color(0xFF14B8A6), size: 20),
                ),
                const SizedBox(width: 12),
                Text(
                  'Themes',
                  style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.w600),
                ),
              ],
            ),
            const SizedBox(height: 16),
            Wrap(
              spacing: 8,
              runSpacing: 8,
              children: themes.map((t) => Chip(
                label: Text(t),
                backgroundColor: theme.colorScheme.surfaceContainerHighest,
              )).toList(),
            ),
          ],
        ),
      ),
    );
  }
}

